#!/usr/bin/env python3
"""Build complete, versioned multilingual benchmark panels.

The panel is the intersection of trained language-script subsets and locally
available benchmark tasks. Dataset aliases are explicit. Taxi1500 editions are
filtered by dominant Unicode script, require at least 900 labeled verses, and
are pinned by archive member name for reproducibility.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
import zipfile
from pathlib import Path

import regex


LANGUAGE_ALIASES = {
    "cmn_Hani": "zho_Hans",
    "ekk_Latn": "est_Latn",
    "fas_Arab": "pes_Arab",
    "gug_Latn": "grn_Latn",
    "yue_Hani": "yue_Hant",
}
TAXI_ALIASES = {"fas_Arab": "pes_Arab"}
SCRIPT_NAMES = {
    "Arab": ("Arabic",),
    "Armn": ("Armenian",),
    "Beng": ("Bengali",),
    "Copt": ("Coptic",),
    "Cyrl": ("Cyrillic",),
    "Deva": ("Devanagari",),
    "Ethi": ("Ethiopic",),
    "Geor": ("Georgian",),
    "Grek": ("Greek",),
    "Guru": ("Gurmukhi",),
    "Hang": ("Hangul",),
    "Hani": ("Han",),
    "Hebr": ("Hebrew",),
    "Jpan": ("Han", "Hiragana", "Katakana"),
    "Khmr": ("Khmer",),
    "Knda": ("Kannada",),
    "Latn": ("Latin",),
    "Mymr": ("Myanmar",),
    "Olck": ("Ol_Chiki",),
    "Sinh": ("Sinhala",),
    "Taml": ("Tamil",),
    "Telu": ("Telugu",),
    "Tfng": ("Tifinagh",),
    "Thai": ("Thai",),
    "Tibt": ("Tibetan",),
}
LETTER_PATTERN = regex.compile(r"\p{L}")
SCRIPT_PATTERNS = {
    script: tuple(regex.compile(rf"\p{{Script={name}}}") for name in names)
    for script, names in SCRIPT_NAMES.items()
}


def _repo_root() -> Path:
    for parent in Path(__file__).resolve().parents:
        if (parent / "configs" / "pipeline").exists():
            return parent
    raise SystemExit("Could not locate repository root")


def _panel_languages(path: Path) -> list[str]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    languages = sorted({str(row["subset"]).strip() for row in rows if str(row.get("subset", "")).strip()})
    if not languages:
        raise SystemExit(f"No language subsets found in {path}")
    return languages


def _task_names(config_dir: Path, prefix: str) -> set[str]:
    tasks: set[str] = set()
    for path in config_dir.glob(f"{prefix}*.yaml"):
        header = path.read_text(encoding="utf-8")[:200]
        if "build_full_multilingual_eval_panel.py" in header:
            continue
        tasks.add(path.stem.removeprefix(prefix))
    return tasks


def _write_simple_alias_config(
    output_path: Path,
    *,
    include: str,
    task: str,
    dataset_name: str,
) -> None:
    output_path.write_text(
        "\n".join(
            [
                "# Generated by pipeline_tools/build_full_multilingual_eval_panel.py",
                f"include: {include}",
                f"task: {task}",
                f"dataset_name: {dataset_name}",
                "",
            ]
        ),
        encoding="utf-8",
    )


def _write_task_alias(source: Path, destination: Path, task: str) -> None:
    """Copy a canonical lm-eval task config while giving the alias a new task id.

    Task templates can define required evaluation splits in addition to their
    dataset name.  Aliases therefore must preserve the entire canonical task
    configuration rather than reconstructing a minimal subset of its fields.
    """
    content = source.read_text(encoding="utf-8")
    content, replacements = re.subn(r"^task:\s*.*$", f"task: {task}", content, count=1, flags=re.MULTILINE)
    if replacements != 1:
        raise SystemExit(f"Could not replace task field in {source}")
    destination.write_text(
        "# Alias generated by pipeline_tools/build_full_multilingual_eval_panel.py\n" + content,
        encoding="utf-8",
    )


def _english_label_ids(labels_dir: Path) -> set[str]:
    ids: set[str] = set()
    for split in ("train", "validation", "test"):
        with (labels_dir / f"{split}.tsv").open(newline="", encoding="utf-8") as handle:
            for row in csv.reader(handle, delimiter="\t"):
                if len(row) >= 3:
                    ids.add(row[0].strip())
    if not ids:
        raise SystemExit(f"No Taxi1500 label IDs found in {labels_dir}")
    return ids


def _taxi_members(zf: zipfile.ZipFile, iso: str) -> list[str]:
    members: list[str] = []
    for name in zf.namelist():
        if not name.endswith(".txt"):
            continue
        base = name.rsplit("/", 1)[-1]
        if base.startswith(f"{iso}_") or base.startswith(f"{iso}-"):
            members.append(name)
    return sorted(members)


def _taxi_rows(zf: zipfile.ZipFile, member: str) -> dict[str, str]:
    rows: dict[str, str] = {}
    with zf.open(member) as handle:
        for raw_line in handle:
            line = raw_line.decode("utf-8", errors="replace").rstrip("\n")
            if not line or line.startswith("#") or "\t" not in line:
                continue
            verse_id, verse = line.split("\t", 1)
            rows[verse_id.strip()] = verse.strip()
    return rows


def _script_fraction(text: str, script: str) -> float:
    try:
        patterns = SCRIPT_PATTERNS[script]
    except KeyError as exc:
        raise SystemExit(f"Unsupported script in training panel: {script}") from exc
    letter_count = len(LETTER_PATTERN.findall(text))
    if letter_count == 0:
        return 0.0
    target_count = sum(
        1
        for pattern in patterns
        for character in pattern.findall(text)
        if LETTER_PATTERN.fullmatch(character)
    )
    return target_count / letter_count


def _best_taxi_member(
    zf: zipfile.ZipFile,
    *,
    lang_script: str,
    label_ids: set[str],
) -> dict[str, object] | None:
    iso, script = lang_script.split("_", 1)
    best: tuple[tuple[int, int, str], float] | None = None
    for member in _taxi_members(zf, iso):
        rows = _taxi_rows(zf, member)
        fraction = _script_fraction(" ".join(rows.values()), script)
        if fraction < 0.5:
            continue
        score = (len(label_ids & set(rows)), len(rows), member)
        if best is None or score > best[0]:
            best = (score, fraction)
    if best is None or best[0][0] < 900:
        return None
    return {
        "member_name": best[0][2],
        "labeled_overlap": best[0][0],
        "total_verses": best[0][1],
        "script_fraction": best[1],
    }


def _sha256_lines(lines: list[str]) -> str:
    payload = "\n".join(lines) + "\n"
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _build_panel(
    *,
    root: Path,
    panel_size: int,
    output_dir: Path,
    taxi_zip: Path,
    taxi_labels_dir: Path,
) -> dict[str, object]:
    languages = _panel_languages(root / f"result_analysis/l2v_nested_samples/{panel_size}.csv")
    harness_tasks = root / "scripts/eval/latest_checkpoint/lm-evaluation-harness/lm_eval/tasks"
    bele_dir = harness_tasks / "belebele"
    sib_dir = harness_tasks / "sib200/configs"
    flores_dir = harness_tasks / "flores_en_perplexity/configs"
    taxi_dir = harness_tasks / "taxi1500/configs"
    taxi_dir.mkdir(parents=True, exist_ok=True)

    bele_available = _task_names(bele_dir, "belebele_")
    sib_available = _task_names(sib_dir, "sib200_")
    flores_available = _task_names(flores_dir, "flores_en_perplexity_")

    tasks: dict[str, list[str]] = {
        "Belebele": [],
        "FLORES": [],
        "SIB200": [],
        "Taxi1500": [],
    }
    aliases_used: list[dict[str, str]] = []

    for language in languages:
        benchmark_language = language if language in bele_available else LANGUAGE_ALIASES.get(language)
        if benchmark_language in bele_available:
            task = f"belebele_{language}"
            if benchmark_language != language:
                _write_task_alias(
                    bele_dir / f"belebele_{benchmark_language}.yaml",
                    bele_dir / f"{task}.yaml",
                    task,
                )
                aliases_used.append(
                    {"benchmark": "Belebele", "panel": language, "dataset": str(benchmark_language)}
                )
            tasks["Belebele"].append(task)

        benchmark_language = language if language in sib_available else LANGUAGE_ALIASES.get(language)
        if benchmark_language in sib_available:
            task = f"sib200_{language}"
            if benchmark_language != language:
                _write_simple_alias_config(
                    sib_dir / f"{task}.yaml",
                    include="../sib200_common",
                    task=task,
                    dataset_name=str(benchmark_language),
                )
                aliases_used.append(
                    {"benchmark": "SIB200", "panel": language, "dataset": str(benchmark_language)}
                )
            tasks["SIB200"].append(task)

        benchmark_language = language
        forward = f"eng_Latn-{benchmark_language}"
        backward = f"{benchmark_language}-eng_Latn"
        if forward not in flores_available or backward not in flores_available:
            benchmark_language = LANGUAGE_ALIASES.get(language, "")
            forward = f"eng_Latn-{benchmark_language}"
            backward = f"{benchmark_language}-eng_Latn"
        if forward in flores_available and backward in flores_available:
            target_forward = f"flores_en_perplexity_eng_Latn-{language}"
            target_backward = f"flores_en_perplexity_{language}-eng_Latn"
            if benchmark_language != language:
                _write_task_alias(
                    flores_dir / f"flores_en_perplexity_{forward}.yaml",
                    flores_dir / f"{target_forward}.yaml",
                    target_forward,
                )
                _write_task_alias(
                    flores_dir / f"flores_en_perplexity_{backward}.yaml",
                    flores_dir / f"{target_backward}.yaml",
                    target_backward,
                )
                aliases_used.append(
                    {"benchmark": "FLORES", "panel": language, "dataset": str(benchmark_language)}
                )
            tasks["FLORES"].extend([target_forward, target_backward])

    taxi_audit: dict[str, dict[str, object]] = {}
    label_ids = _english_label_ids(taxi_labels_dir)
    with zipfile.ZipFile(taxi_zip) as zf:
        for language in languages:
            dataset_language = TAXI_ALIASES.get(language, language)
            selection = _best_taxi_member(
                zf,
                lang_script=dataset_language,
                label_ids=label_ids,
            )
            if selection is None:
                continue
            task = f"taxi1500_v2_{language}"
            (taxi_dir / f"{task}.yaml").write_text(
                "\n".join(
                    [
                        "# Generated by pipeline_tools/build_full_multilingual_eval_panel.py",
                        "include: ../taxi1500_common",
                        f"task: {task}",
                        "dataset_kwargs:",
                        f"  lang_script: {dataset_language}",
                        "  corpus_version: v3.0",
                        "  min_labeled_examples: 900",
                        f"  member_name: {json.dumps(selection['member_name'])}",
                        "",
                    ]
                ),
                encoding="utf-8",
            )
            tasks["Taxi1500"].append(task)
            taxi_audit[language] = {
                "dataset_language": dataset_language,
                **selection,
            }
            if dataset_language != language:
                aliases_used.append(
                    {"benchmark": "Taxi1500", "panel": language, "dataset": dataset_language}
                )

    ordered_tasks = [
        *sorted(tasks["Belebele"]),
        *sorted(tasks["FLORES"]),
        *sorted(tasks["SIB200"]),
        *sorted(tasks["Taxi1500"]),
    ]
    task_file = output_dir / f"lm_eval_tasks_{panel_size}_langs_v2.txt"
    task_file.write_text("\n".join(ordered_tasks) + "\n", encoding="utf-8")
    summary = {
        "panel_size": panel_size,
        "language_subsets": languages,
        "num_language_subsets": len(languages),
        "task_file": str(task_file),
        "task_sha256": _sha256_lines(ordered_tasks),
        "num_tasks": len(ordered_tasks),
        "task_breakdown": {benchmark: len(values) for benchmark, values in tasks.items()},
        "aliases_used": aliases_used,
        "taxi1500": {
            "corpus": str(taxi_zip),
            "minimum_labeled_examples": 900,
            "minimum_dominant_script_fraction": 0.5,
            "selections": taxi_audit,
        },
    }
    (output_dir / f"lm_eval_tasks_{panel_size}_langs_v2.summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    return summary


def main() -> int:
    root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--panels", default="96,200")
    parser.add_argument(
        "--output-dir",
        default=str(root / "configs/benchmark_panels/v2"),
    )
    parser.add_argument(
        "--taxi-zip",
        default=str(Path.home() / ".cache/moe-study/taxi1500/raw/Taxi1500-c_v3.0.zip"),
    )
    parser.add_argument(
        "--taxi-labels-dir",
        default=str(Path.home() / ".cache/moe-study/taxi1500/english_labels"),
    )
    args = parser.parse_args()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    summaries = [
        _build_panel(
            root=root,
            panel_size=int(panel),
            output_dir=output_dir,
            taxi_zip=Path(args.taxi_zip).resolve(),
            taxi_labels_dir=Path(args.taxi_labels_dir).resolve(),
        )
        for panel in args.panels.split(",")
        if panel.strip()
    ]
    manifest = {
        "schema_version": 1,
        "method": "trained language-script intersection with explicit aliases and pinned Taxi1500 editions",
        "panels": summaries,
    }
    (output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    for summary in summaries:
        print(
            f"[OK] panel={summary['panel_size']} tasks={summary['num_tasks']} "
            f"breakdown={summary['task_breakdown']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
